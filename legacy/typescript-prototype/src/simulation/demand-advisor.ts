import type { CityMetrics } from '../types';

export type DemandAdvisor = {
  focus: 'residential' | 'commercial' | 'industrial' | 'balanced';
  urgency: 'low' | 'medium' | 'high';
  text: string;
};

export function demandAdvisor(metrics: CityMetrics): DemandAdvisor {
  const entries = [
    { key: 'residential' as const, value: metrics.demand.residential },
    { key: 'commercial' as const, value: metrics.demand.commercial },
    { key: 'industrial' as const, value: metrics.demand.industrial },
  ].sort((a, b) => b.value - a.value);

  const top = entries[0];
  if (top.value < 45) {
    return {
      focus: 'balanced',
      urgency: 'low',
      text: '??????????????????????????',
    };
  }

  if (top.key === 'residential') {
    return {
      focus: 'residential',
      urgency: top.value >= 70 ? 'high' : 'medium',
      text:
        metrics.serviceCoverage < 50
          ? '???????????????????????'
          : '???????????????????????????',
    };
  }

  if (top.key === 'commercial') {
    return {
      focus: 'commercial',
      urgency: top.value >= 65 ? 'high' : 'medium',
      text:
        metrics.population < 40
          ? '????????????????????'
          : '???????????????????????',
    };
  }

  return {
    focus: 'industrial',
    urgency: top.value >= 65 ? 'high' : 'medium',
    text:
      metrics.pollution > 12
        ? '??????????????????????'
        : '?????????????????????????',
  };
}
